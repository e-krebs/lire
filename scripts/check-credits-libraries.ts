import { existsSync, readFileSync, writeFileSync } from "node:fs";
import {
  buildLibraries,
  type Library,
  type LibraryGroup,
  type PackageInfo,
} from "../src/shared/credits/buildLibraries.ts";

const OUTPUT = "src/client/components/app/credits/libraries.ts";
const WRITE = process.argv.includes("--write");

const LABELS: Record<string, string> = { dompurify: "DOMPurify", zod: "Zod" };
const GROUPS: LibraryGroup[] = [
  { pattern: /^@dnd-kit\//, label: "dnd kit", homepage: "https://dndkit.com" },
  { pattern: /^@tanstack\//, label: "TanStack", homepage: "https://tanstack.com" },
  { pattern: /^react(-dom)?$/, label: "React", homepage: "https://react.dev" },
];

const readPackage = (name: string): PackageInfo => {
  const { license, homepage } = JSON.parse(
    readFileSync(`node_modules/${name}/package.json`, "utf8"),
  ) as { license?: unknown; homepage?: string };
  if (typeof license !== "string") {
    throw new Error(`${name}: node_modules/${name}/package.json has no string "license"`);
  }
  return { license, homepage };
};

const render = (libraries: Library[]): string => {
  const entries = libraries.map(({ label, license, homepage }) =>
    [
      "  {",
      `    label: ${JSON.stringify(label)},`,
      `    license: ${JSON.stringify(license)},`,
      ...(homepage ? [`    homepage: ${JSON.stringify(homepage)},`] : []),
      "  },",
    ].join("\n"),
  );
  return [
    `import type { Library } from "shared/credits/buildLibraries";`,
    "",
    "// Generated by `yarn credits:libraries`; `yarn check:credits` fails when it is stale.",
    "export const LIBRARIES: readonly Library[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
};

const { dependencies = {} } = JSON.parse(readFileSync("package.json", "utf8")) as {
  dependencies?: Record<string, string>;
};
const packages = Object.fromEntries(
  Object.keys(dependencies).map((name) => [name, readPackage(name)]),
);
const libraries = buildLibraries({ packages, groups: GROUPS, labels: LABELS });
const expected = render(libraries);

if (WRITE) {
  writeFileSync(OUTPUT, expected);
  console.log(`wrote ${OUTPUT}: ${libraries.length} lines`);
} else {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, "utf8") : undefined;
  if (current !== expected) {
    console.error(`${OUTPUT} is out of step with the runtime dependencies in package.json.`);
    console.error("Fix: yarn credits:libraries");
    process.exit(1);
  }
  console.log(
    `credits libraries gate: ${libraries.length} lines from ${Object.keys(packages).length} dependencies clean`,
  );
}
